// Detect language from Zustand store if present
const getInitialLanguage = () => {
  try {
    const storage = localStorage.getItem('dev-voice-storage');
    if (storage) {
      const state = JSON.parse(storage);
      return state.state?.settings?.language || 'en';
    }
  } catch (e) {
    console.warn("Failed to parse language from store", e);
  }
  return 'en';
};

i18n.use(LanguageDetector).use(initReactI18next).init({ 
  resources, 
  lng: getInitialLanguage(),
  fallbackLng: 'en', 
  interpolation: { escapeValue: false },
  detection: {
    order: ['querystring', 'cookie', 'localStorage', 'navigator'],
    caches: ['localStorage', 'cookie']
  }
});

